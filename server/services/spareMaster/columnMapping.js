/**
 * Excel column -> canonical field map for the Spare Master importer.
 *
 * This file is the versioning seam. When a future export renames a column, add
 * the new header to that field's `aliases` and nothing else in the importer
 * changes. Aliases are matched case-insensitively with whitespace collapsed, so
 * "Parts Number", "PARTSNUMBER " and "parts number" all reach the same field.
 *
 * `canonical` names are the importer's own vocabulary, not schema paths — the
 * transformer decides where each one lands, because several of them (the price
 * columns, the equipment columns) collapse into one nested schema structure.
 */

const normalizeHeader = (header) =>
  String(header ?? "")
    .trim()
    .toUpperCase()
    .replace(/\s+/g, " ");

