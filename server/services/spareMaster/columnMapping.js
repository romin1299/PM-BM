/**
 * Alias -> canonical, built once at module load. Two fields must never claim the
 * same header, so a collision here is a bug in the map above rather than bad
 * input, and it is worth failing loudly at startup instead of silently letting
 * one field win.
 */
const ALIAS_TO_CANONICAL = new Map();

Object.entries(SPARE_MASTER_COLUMNS).forEach(([canonical, { aliases }]) => {
  aliases.forEach((alias) => {
    const key = normalizeHeader(alias);
    if (ALIAS_TO_CANONICAL.has(key))
      throw new Error(
        `Duplicate Spare Master column alias "${alias}" claimed by both "${ALIAS_TO_CANONICAL.get(key)}" and "${canonical}"`,
      );
    ALIAS_TO_CANONICAL.set(key, canonical);
  });
});

const REQUIRED_CANONICAL_FIELDS = Object.entries(SPARE_MASTER_COLUMNS)
  .filter(([, def]) => def.required)
  .map(([canonical]) => canonical);

/**
 * Turns a sheet's header cells into { canonicalField: columnIndex }.
 * Unknown headers are ignored by design — the legacy export carries ~30 columns
 * that are entirely empty and another handful that are constant, and none of
 * them should be treated as an error.
 */
const buildHeaderIndex = (headerCells = []) => {
  const index = {};
  headerCells.forEach((text, columnIndex) => {
    const canonical = ALIAS_TO_CANONICAL.get(normalizeHeader(text));
    if (canonical && index[canonical] === undefined) index[canonical] = columnIndex;
  });
  return index;
};

const countRecognisedColumns = (headerCells = []) =>
  Object.keys(buildHeaderIndex(headerCells)).length;

module.exports = {
  SPARE_MASTER_COLUMNS,
  REQUIRED_CANONICAL_FIELDS,
  normalizeHeader,
  buildHeaderIndex,
  countRecognisedColumns,
};
